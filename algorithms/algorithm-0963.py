def linear_search_0963_0001(values, target):
    for index, value in enumerate(values):
        if value == target:
            return index
    return -1

def interpolation_search_0963_0002(values, target):
    low = 0
    high = len(values) - 1
    while low <= high and values[low] <= target <= values[high]:
        if values[high] == values[low]:
            return low if values[low] == target else -1
        position = low + (target - values[low]) * (high - low) // (values[high] - values[low])
        if values[position] == target:
            return position
        if values[position] < target:
            low = position + 1
        else:
            high = position - 1
    return -1

def binary_search_0963_0003(values, target):
    low = 0
